@st.cache_resource(show_spinner="Loading prediction model...")
def load_artifacts():
    required = ["final_dnn.keras", "final_preprocessor.joblib", "final_label_encoder.joblib", "final_model_metadata.json"]
    missing = [name for name in required if not (MODEL_DIR / name).is_file()]
    if missing:
        raise FileNotFoundError("Missing models/ files: " + ", ".join(missing))
    model = tf.keras.models.load_model(MODEL_DIR / "final_dnn.keras")
    # Load only joblib artifacts generated by your own trusted notebooks.
    preprocessor = joblib.load(MODEL_DIR / "final_preprocessor.joblib")
    encoder = joblib.load(MODEL_DIR / "final_label_encoder.joblib")
    metadata = json.loads((MODEL_DIR / "final_model_metadata.json").read_text(encoding="utf-8"))
    if list(metadata["class_names"]) != list(encoder.classes_):
        raise ValueError("Saved class mapping does not match the label encoder.")
    return model, preprocessor, encoder, metadata

st.markdown('''<div class="hero"><div class="eyebrow">ACADEMIC INSIGHTS · DEEP LEARNING</div>
<h1>Student Performance Predictor</h1><p>Estimate final academic performance using early-term grades and student context. Built with a trained Deep Neural Network and a reproducible preprocessing pipeline.</p></div>''', unsafe_allow_html=True)

try:
    model, preprocessor, label_encoder, metadata = load_artifacts()
except Exception as exc:
    st.error(f"Could not load the saved model: {exc}")
    st.info("Place the four files created in Notebook 05 inside a `models/` folder next to `app.py`, then refresh.")
    st.stop()

features = metadata["selected_features"]
numeric = set(metadata["numeric_features"])
cat_options = metadata["categorical_options_from_training"]
ranges = metadata["numeric_ranges_from_training"]

LABELS = {
    "G1": "First period grade (G1)", "G2": "Second period grade (G2)",
    "failures": "Previous class failures", "higher": "Plans for higher education",
    "absences": "Number of school absences", "studytime": "Weekly study time",
    "school": "School", "Fedu": "Father's education level",
    "Medu": "Mother's education level", "Mjob": "Mother's occupation",
    "Dalc": "Workday alcohol consumption", "famrel": "Family relationship quality"
}
HELP = {
    "G1": "First grading-period score, from 0 to 20.",
    "G2": "Second grading-period score, from 0 to 20. This app predicts after G2 is known.",
    "failures": "Number of previous class failures, as recorded in the dataset (0 to 4).",
    "studytime": "1: <2 hours; 2: 2–5 hours; 3: 5–10 hours; 4: >10 hours per week.",
    "Fedu": "0: none; 1: primary (4th grade); 2: 5th–9th; 3: secondary; 4: higher education.",
    "Medu": "0: none; 1: primary (4th grade); 2: 5th–9th; 3: secondary; 4: higher education.",
    "Dalc": "1: very low; 5: very high.",
    "famrel": "1: very bad; 5: excellent.",
    "absences": "Total school absences recorded so far."
}
OPTIONS = {
    "higher": {"yes": "Yes", "no": "No"},
    "school": {"GP": "Gabriel Pereira (GP)", "MS": "Mousinho da Silveira (MS)"},
    "Mjob": {"teacher": "Teacher", "health": "Healthcare", "services": "Civil services / services", "at_home": "At home", "other": "Other"},
}

left, right = st.columns([1.65, 1], gap="large")
with left:
    st.markdown('<div class="section-kicker">01 / STUDENT PROFILE</div>', unsafe_allow_html=True)
    st.subheader("Enter student details")
    st.caption("Only the 12 model-selected features are requested. Fields match the original training dataset.")
    with st.form("student_prediction", clear_on_submit=False):
        values = {}
        # Keep form grouping intuitive without changing the feature order used for inference.
        grade_fields = [f for f in ["G1", "G2", "failures", "absences", "studytime"] if f in features]
        context_fields = [f for f in features if f not in grade_fields]
        st.markdown("**Academic information**")
        cols = st.columns(2)
        for i, feature in enumerate(grade_fields):
            with cols[i % 2]:
                spec = ranges[feature]
                lo, hi = int(spec["min"]), int(spec["max"])
                default = 10 if feature in {"G1", "G2"} else lo
                if feature == "studytime": default = 2
                values[feature] = st.number_input(LABELS.get(feature, feature), min_value=lo, max_value=hi,
                    value=min(max(default, lo), hi), step=1, help=HELP.get(feature), key=f"f_{feature}")
        st.divider()
        st.markdown("**Background and personal context**")
        cols = st.columns(2)
        for i, feature in enumerate(context_fields):
            with cols[i % 2]:
                if feature in numeric:
                    spec = ranges[feature]
                    lo, hi = int(spec["min"]), int(spec["max"])
                    default = 3 if feature in {"Fedu", "Medu", "famrel"} else lo
                    values[feature] = st.number_input(LABELS.get(feature, feature), min_value=lo, max_value=hi,
                        value=min(max(default, lo), hi), step=1, help=HELP.get(feature), key=f"f_{feature}")
                else:
                    available = cat_options[feature]
                    display = OPTIONS.get(feature, {})
                    values[feature] = st.selectbox(LABELS.get(feature, feature), available,
                        format_func=lambda x, d=display: d.get(x, x.replace("_", " ").title()),
                        key=f"f_{feature}")
        submitted = st.form_submit_button("Predict academic performance", type="primary", use_container_width=True)

with right:
    st.markdown('<div class="section-kicker">02 / MODEL OVERVIEW</div>', unsafe_allow_html=True)
    st.subheader("Prediction guide")
    st.markdown("**Three performance categories**")
    st.markdown("🔴 **Low:** Final grade 0–9  \n🟡 **Average:** Final grade 10–13  \n🟢 **Good:** Final grade 14–20")
    st.divider()
    st.markdown("**How it works**")
    st.write("1. Enter the student's known details and G1/G2 grades.\n\n2. Saved preprocessing converts the inputs to the same representation used in training.\n\n3. The DNN estimates a probability for each performance category.")
    st.divider()
    st.info("This model predicts **final G3 performance after G2 is available**. It does not predict a student's future performance before the school year begins.")
    st.caption("Research demonstration · UCI Portuguese-course student dataset (649 records). Not intended for admissions, hiring or consequential academic decisions.")

if submitted:
    try:
        row = pd.DataFrame([{f: values[f] for f in features}], columns=features)
        transformed = preprocessor.transform(row).astype("float32")
        probabilities = np.asarray(model.predict(transformed, verbose=0))[0]
        if len(probabilities) != len(label_encoder.classes_) or not np.isfinite(probabilities).all():
            raise ValueError("Model returned invalid prediction probabilities.")
        best_idx = int(np.argmax(probabilities))
        predicted = str(label_encoder.inverse_transform([best_idx])[0])
        class_probs = {str(label): float(probabilities[i]) for i, label in enumerate(label_encoder.classes_)}
    except Exception as exc:
        st.error(f"Prediction failed: {exc}")
    else:
        st.divider()
        st.markdown('<div class="section-kicker">03 / PREDICTION RESULTS</div>', unsafe_allow_html=True)
        st.subheader("Estimated academic performance")
        st.markdown(f'<div class="result-panel"><div class="result-label">Predicted G3 category</div><div class="result-value">{predicted}</div><div class="small-note">Estimated probability of this category: {class_probs[predicted]:.1%}. These are model outputs, not calibrated certainty.</div></div>', unsafe_allow_html=True)
        cols = st.columns(3)
        for col, label in zip(cols, ["Low", "Average", "Good"]):
            with col:
                st.metric(label, f"{class_probs[label]:.1%}")
                st.progress(min(max(class_probs[label], 0.0), 1.0))
        if predicted == "Low":
            st.warning("The model suggests possible academic difficulty. Consider a supportive conversation and additional learning resources; do not treat this prediction as a diagnosis or final judgment.")
        elif predicted == "Average":
            st.info("The model estimates average-range final performance. Study habits and learning support can still make a difference.")
        else:
            st.success("The model estimates good-range final performance. This is a prediction, not a guaranteed outcome.")
        st.caption("Final DNN held-out test accuracy: 82.31% (107/130 students). Small dataset; performance may differ outside the original dataset.")

st.divider()
st.caption("Academic project • DNN + scikit-learn preprocessing + Streamlit • Predictions should support, never replace, human judgment.")
